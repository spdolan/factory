def gather(env: dict) -> dict:  # pragma: no cover - talks to GitHub; exercised in the test repository
    """Build resolve()'s context from the Actions environment."""
    import subprocess
    from common import gh, gh_json
    repo = env["GITHUB_REPOSITORY"]
    event = json.loads(Path(env["GITHUB_EVENT_PATH"]).read_text()) if env.get("GITHUB_EVENT_PATH") else {}
    params = json.loads(env.get("PARAMS") or "{}") or {}
    pipeline = load_pipeline()
    st = pipeline["stages"].get(env["STAGE"])
    if st is None:
        raise FactoryError(f"no stage '{env['STAGE']}'")
    default_branch = (event.get("repository") or {}).get("default_branch") or \
        gh("api", f"repos/{repo}", "--jq", ".default_branch").strip()
    raw = gh("api", "-H", "Accept: application/vnd.github.raw", f"repos/{repo}/contents/.github/factory/config.yml?ref={default_branch}",
             check=False)
    config = load_yaml_text(raw, "config.yml") if raw.strip() and not raw.lstrip().startswith('{"message"') else None
    item = {}
    if st["item"] == "issue":
        n = params.get("issue_number") or (event.get("issue") or {}).get("number")
        if n:
            import tracker
            item = tracker.get(int(n))
    elif st["item"] == "pr":
        n = params.get("pr_number") or (event.get("pull_request") or {}).get("number")
        if n:
            pr = gh_json("api", f"repos/{repo}/pulls/{int(n)}")
            item = {"number": pr["number"], "labels": [x["name"] for x in pr["labels"]], "state": pr["state"],
                    "draft": pr["draft"], "head_ref": pr["head"]["ref"], "base_sha": pr["base"]["sha"],
                    "head_sha": pr["head"]["sha"], "changed_lines": pr["additions"] + pr["deletions"]}
    files = {}
    if st.get("requires_file"):
        files[st["requires_file"]] = Path(st["requires_file"]).exists()
    fac_repo = env.get("FACTORY_REPO", "")
    tags = {}
    try:
        url = f"{env.get('GITHUB_SERVER_URL', 'https://github.com')}/{fac_repo}.git"
        out = subprocess.run(["git", "-C", ".factory", "ls-remote", "--tags", "--refs", "origin"], capture_output=True, text=True,
                             timeout=60).stdout or subprocess.run(["git", "ls-remote", "--tags", "--refs", url],
                                                                   capture_output=True, text=True, timeout=60).stdout
        for line in out.splitlines():
            sha, _, ref = line.partition("\t")
            tags[ref.removeprefix("refs/tags/")] = sha
    except (OSError, subprocess.SubprocessError):
        pass
    sha = env.get("FACTORY_SHA", "")
    release = next((t for t, s in sorted(tags.items()) if s == sha and parse_version(t) and len(parse_version(t)) == 3), "")
    return {"stage": env["STAGE"], "event_name": env.get("GITHUB_EVENT_NAME", ""), "event": event, "params": params,
            "variables": json.loads(env.get("VARS_JSON") or "{}") or {}, "config": config, "item": item,
            "repository": repo, "server_url": env.get("GITHUB_SERVER_URL", "https://github.com"),
            "run_id": env.get("GITHUB_RUN_ID", ""), "dry_run": env.get("DRY_RUN") == "true", "files": files, "tags": tags,
            "factory": {"repo": fac_repo, "sha": sha, "ref": env.get("FACTORY_REF", ""), "release": release}}


def cmd_plan(args) -> int:  # pragma: no cover - IO
    plan = resolve(gather(dict(os.environ)))
    Path(args.out).write_text(json.dumps(plan, indent=2) + "\n")
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a") as fh:
            fh.write(summary(plan))
    if os.environ.get("GITHUB_OUTPUT"):
        a = plan.get("agent") or {}
        with open(os.environ["GITHUB_OUTPUT"], "a") as fh:
            simple = {"run": str(plan["run"]).lower(), "runtime": plan["runtime"], "item": plan["item"],
                      "agent": "true" if a else "false", "output": plan["output"]["kind"], "model": a.get("model", ""),
                      "effort": a.get("effort", ""), "timeout": plan["timeout"], "setup": str(a.get("setup", False)).lower(),
                      "bun": str(a.get("bun", False)).lower(), "skill": a.get("skill", ""), "apply": ",".join(plan["apply"]),
                      "settle_seconds": plan["settle_seconds"],
                      "base_sha": (plan.get("pr") or {}).get("base_sha", ""), "head_sha": (plan.get("pr") or {}).get("head_sha", ""),
                      "setting_sources": (plan.get("local") or {}).get("setting_sources", ""),
                      "work_dir": (plan.get("local") or {}).get("work_dir", ""),
                      "session_name": (plan.get("local") or {}).get("session_name", ""),
                      "worktree": (plan.get("local") or {}).get("worktree", ""),
                      "allowed_tools": a.get("allowed_tools", ""), "gate_awaiting": load_pipeline()["gate"]["awaiting"]}
            for k, v in simple.items():
                fh.write(f"{k}={v}\n")
            for k, v in (("claude_args", plan["claude_args"]), ("prompt", plan["prompt"]),
                         ("plan", json.dumps(plan, separators=(",", ":")))):
                delim = "FACTORY_" + hashlib.sha256(v.encode()).hexdigest()[:16]
                fh.write(f"{k}<<{delim}\n{v}\n{delim}\n")
    print(f"{plan['stage']}: {'runs' if plan['run'] else 'skipped'}: {plan['reason']}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("plan")
    p.add_argument("--out", default="plan.json")
    r = sub.add_parser("render-stubs")
    r.add_argument("--uses", required=True)
    r.add_argument("--ref", required=True)
    r.add_argument("--out", required=True)
    c = sub.add_parser("check-stubs")
    c.add_argument("dir")
    v = sub.add_parser("validate-config")
    v.add_argument("path")
    sub.add_parser("stages")
    args = ap.parse_args()
    if args.cmd == "plan":
        return cmd_plan(args)
    pipeline = load_pipeline()
    if args.cmd == "stages":
        print("\n".join(pipeline["stages"]))
    elif args.cmd == "render-stubs":
        out = Path(args.out)
        out.mkdir(parents=True, exist_ok=True)
        for name in pipeline["stages"]:
            path = out / f"factory-{name}.yml"
            path.write_text(stub_text(pipeline, name, args.uses, args.ref))
            print(path)
    elif args.cmd == "check-stubs":
        lines, ok = check_stubs(Path(args.dir))
        print("\n".join(lines))
        return 0 if ok else 1
    elif args.cmd == "validate-config":
        path = Path(args.path)
        if not path.exists():
            print(f"no {path}: factory defaults apply")
            return 0
        cfg = load_yaml_text(path.read_text(), str(path))
        problems, warnings = validate_config(cfg, pipeline, load_features())
        for w in warnings:
            print(f"warning  {w}")
        for x in problems:
            print(f"problem  {x}")
        if not problems:
            print(f"ok       {path}")
        return 1 if problems else 0
    return 0


