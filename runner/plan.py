"""The plan interpreter: pipeline.yaml + config.yml + variables + the event → one stage's plan.

Commands:
  plan              resolve the stage named by $STAGE for this run (the plan job; see cmd_plan)
  render-stubs      --uses OWNER/NAME --ref REF --out DIR: one stub per stage
  check-stubs DIR   are the stubs unedited, and do they all call one ref?
  validate-config PATH
  stages            the stage names

Everything above the IO section is pure and covered by runner/tests (golden plans per stage).
"""

