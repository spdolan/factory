SECRETS = ["ANTHROPIC_API_KEY", "CLAUDE_CODE_OAUTH_TOKEN", "FACTORY_GITHUB_TOKEN", "FACTORY_READ_TOKEN"]
PERMISSION_ORDER = ["contents", "issues", "pull-requests", "packages", "actions", "id-token"]
SAFE = re.compile(r"^[A-Za-z0-9._:/@+-]+$")

# --- stubs -------------------------------------------------------------------------------------

STUB_HEADER = "# Generated by `factory install`; edit .github/factory/config.yml, not this file."


def q(value) -> str:
    """A YAML scalar: JSON strings are valid YAML double-quoted strings."""
    return json.dumps(value) if isinstance(value, str) else json.dumps(value)


def item_input(kind: str) -> tuple[str, str] | None:
    return {"issue": ("issue_number", "Issue number"), "pr": ("pr_number", "Pull request number")}.get(kind)


def stub_body(pipeline: dict, name: str, uses: str, ref: str) -> str:
    st = pipeline["stages"][name]
    issue_types: list[str] = []
    out = [f'name: "Factory: {name}"', "on:"]
    ifs: list[str] = []
    labels: list[str] = []
    for trig in st["triggers"]:
        ev = trig["event"]
        if ev in ("item.opened", "item.labeled"):
            t = "opened" if ev == "item.opened" else "labeled"
            if t not in issue_types:
                issue_types.append(t)
            if ev == "item.labeled":
                labels.append(trig["label"])
            if trig.get("authors"):
                ifs.append(f"github.event_name != 'issues' || vars.{trig['all_authors_variable']} == 'true' || "
                           f"contains(fromJSON('{json.dumps(trig['authors'])}'), github.event.issue.author_association)")
    if issue_types:
        out += ["  issues:", f"    types: [{', '.join(issue_types)}]"]
    if labels:
        ifs.append(f"github.event_name != 'issues' || contains(fromJSON('{json.dumps(labels)}'), github.event.label.name)")
    for trig in st["triggers"]:
        ev = trig["event"]
        if ev == "pr.changed":
            out += ["  pull_request_target:", f"    types: [{', '.join(trig['types'])}]"]
        elif ev == "schedule":
            out += ["  schedule:", f"    - cron: {q(trig['cron'])}"]
        elif ev == "repository_dispatch":
            out += ["  repository_dispatch:", f"    types: [{trig['type']}]"]
        elif ev in ("dispatch", "call"):
            out.append("  workflow_dispatch:" if ev == "dispatch" else "  workflow_call:")
            out.append("    inputs:")
            inputs = dict(trig.get("inputs") or {})
            ii = item_input(st["item"])
            if ii:
                inputs = {ii[0]: {"description": ii[1], "required": True, "type": "number"}, **inputs}
            inputs["dry_run"] = {"description": "Run the plan and agent jobs, but write nothing", "type": "boolean", "default": False}
            for key, spec in inputs.items():
                out.append(f"      {key}:")
                out.append(f"        description: {q(spec['description'])}")
                if spec.get("required"):
                    out.append("        required: true")
                out.append(f"        type: {spec.get('type', 'string')}")
                if "default" in spec:
                    out.append(f"        default: {q(spec['default'])}")
            if ev == "call":
                out.append("    secrets:")
                for s in SECRETS:
                    out += [f"      {s}:", "        required: false"]
    conc = st.get("concurrency")
    if conc is not None:
        group = f"factory-{name}" + (f"-${{{{ {conc['key']} }}}}" if conc.get("key") else "")
        out += ["concurrency:", f"  group: {group}", f"  cancel-in-progress: {str(bool(conc.get('cancel'))).lower()}"]
    out += ["jobs:", f"  {name}:"]
    if ifs:
        out += ["    if: >-", "      " + " &&\n      ".join(f"({c})" for c in ifs)]
    perms = dict(pipeline["permissions_base"])
    perms.update(st.get("permissions") or {})
    out += [f"    uses: {uses}/.github/workflows/stage.yml@{ref}", "    with:", f"      stage: {name}",
            "      params: ${{ toJSON(inputs) }}", "      dry_run: ${{ inputs.dry_run == true }}", "    permissions:"]
    out += [f"      {k}: {perms[k]}" for k in sorted(perms, key=PERMISSION_ORDER.index)]
    out.append("    secrets:")
    out += [f"      {s}: ${{{{ secrets.{s} }}}}" for s in SECRETS]
    return "\n".join(out) + "\n"


def stub_hash(body: str) -> str:
    return hashlib.sha256(body.encode()).hexdigest()[:12]


def stub_text(pipeline: dict, name: str, uses: str, ref: str) -> str:
    if not SAFE.match(uses) or uses.count("/") != 1 or not SAFE.match(ref):
        raise FactoryError(f"bad --uses {uses!r} or --ref {ref!r}")
    body = stub_body(pipeline, name, uses, ref)
    return f"{STUB_HEADER}\n# factory-stub: {name} {ref} {stub_hash(body)}\n{body}"


def check_stubs(directory: Path) -> tuple[list[str], bool]:
    lines, ok, refs = [], True, set()
    stubs = sorted(directory.glob("factory-*.yml"))
    for path in stubs:
        text = path.read_text(encoding="utf-8").split("\n", 2)
        m = re.match(r"^# factory-stub: (\S+) (\S+) ([0-9a-f]{12})$", text[1] if len(text) > 1 else "")
        if not m:
            lines.append(f"not a stub  {path.name} (no factory-stub header: a 0.1 copy, or edited)")
            ok = False
            continue
        refs.add(m.group(2))
        body = text[2] if len(text) > 2 else ""
        uses = re.search(r"uses: (\S+)/\.github/workflows/stage\.yml@(\S+)", body)
        if stub_hash(body) != m.group(3):
            lines.append(f"edited      {path.name} (re-run `factory update`)")
            ok = False
        elif not uses or uses.group(2) != m.group(2):
            lines.append(f"ref differs {path.name} (header says {m.group(2)})")
            ok = False
        else:
            lines.append(f"ok          {path.name} ({m.group(1)} @ {m.group(2)})")
    if not stubs:
        lines.append(f"no stubs in {directory}")
        ok = False
    if len(refs) > 1:
        lines.append(f"stubs call different refs: {', '.join(sorted(refs))}")
        ok = False
    return lines, ok


# --- config.yml --------------------------------------------------------------------------------

def norm_autonomy(value):
    return "off" if value is False else value


def norm_config(cfg):
    """YAML 1.1 reads `on`/`off` as booleans: `features: {on: [...]}` and `autonomy: off`."""
    if not isinstance(cfg, dict):
        return cfg
    cfg = copy.deepcopy(cfg)
    if "autonomy" in cfg:
        cfg["autonomy"] = norm_autonomy(cfg["autonomy"])
    f = cfg.get("features")
    if isinstance(f, dict):
        cfg["features"] = {("on" if k is True else "off" if k is False else k): v for k, v in f.items()}
    return cfg


def validate_config(cfg, pipeline: dict, features: dict) -> tuple[list[str], list[str]]:
    """(problems, warnings) for a parsed config.yml."""
    p: list[str] = []
    w: list[str] = []
    if cfg is None:
        return p, w
    cfg = norm_config(cfg)
    if not isinstance(cfg, dict):
        return ["config.yml must be a mapping"], w
    top = {"autonomy", "verify", "features", "updates", "tiers", "stages", "runtimes", "effort"}
    for k in cfg:
        if k not in top:
            p.append(f"unknown key '{k}'")
    if "autonomy" in cfg and norm_autonomy(cfg["autonomy"]) not in pipeline["autonomy"]["policies"]:
        p.append(f"autonomy must be one of {', '.join(pipeline['autonomy']['policies'])}")
    if "verify" in cfg and not isinstance(cfg["verify"], bool):
        p.append("verify must be true or false")
    f = cfg.get("features") or {}
    if not isinstance(f, dict):
        p.append("features must be a mapping (preview, on, off)")
        f = {}
    for k, v in f.items():
        if k not in ("preview", "on", "off"):
            p.append(f"unknown key 'features.{k}'")
        elif k == "preview" and v != "all" and not isinstance(v, list):
            p.append("features.preview must be 'all' or a list of flags")
        elif k != "preview" and not isinstance(v, list):
            p.append(f"features.{k} must be a list of flags")
        for flag in v if isinstance(v, list) else []:
            if flag not in features:
                w.append(f"features.{k}: no flag '{flag}' in this factory version")
    u = cfg.get("updates") or {}
    for k, v in (u.items() if isinstance(u, dict) else []):
        if k == "check" and not isinstance(v, bool):
            p.append("updates.check must be true or false")
        elif k == "advance" and v not in ("human", "agent"):
            p.append("updates.advance must be human or agent")
        elif k not in ("check", "advance"):
            p.append(f"unknown key 'updates.{k}'")
    for k, v in (cfg.get("tiers") or {}).items():
        if k not in pipeline["tiers"]:
            p.append(f"unknown tier '{k}'")
        elif not isinstance(v, str) or not SAFE.match(v):
            p.append(f"tiers.{k} must be a model ID")
    for k, v in (cfg.get("effort") or {}).items():
        if k not in pipeline["stages"]:
            p.append(f"effort: unknown stage '{k}'")
        elif v not in EFFORTS:
            p.append(f"effort.{k} must be one of {', '.join(EFFORTS)}")
    for name, s in (cfg.get("stages") or {}).items():
        if name not in pipeline["stages"]:
            p.append(f"unknown stage '{name}'")
            continue
        for k, v in (s or {}).items():
            where = f"stages.{name}.{k}"
            if k in ("tier", "model"):
                if not isinstance(v, str) or not SAFE.match(v):
                    p.append(f"{where} must be a tier or model ID")
            elif k == "effort" and v not in EFFORTS:
                p.append(f"{where} must be one of {', '.join(EFFORTS)}")
            elif k == "enabled" and not isinstance(v, bool):
                p.append(f"{where} must be true or false")
            elif k == "runtime":
                if v not in RUNTIMES:
                    p.append(f"{where} must be one of {', '.join(RUNTIMES)}")
                elif v == "local" and "runtime" not in pipeline["stages"][name]:
                    p.append(f"{where}: {name} can't run locally")
            elif k == "small_change_lines" and not (isinstance(v, int) and v >= 0):
                p.append(f"{where} must be a number")
            elif k == "when":
                for cond, o in (v or {}).items():
                    if cond not in (pipeline["stages"][name].get("when") or {}):
                        p.append(f"{where}.{cond}: {name} has no such condition")
                    for ok, ov in (o or {}).items():
                        if ok not in ("tier", "model", "effort"):
                            p.append(f"{where}.{cond}.{ok}: only tier, model and effort")
            elif k not in ("tier", "model", "effort", "enabled", "runtime", "small_change_lines", "when"):
                p.append(f"unknown key '{where}'")
    loc = ((cfg.get("runtimes") or {}).get("local") or {})
    for k in loc:
        if k not in ("setting_sources", "work_dir"):
            p.append(f"unknown key 'runtimes.local.{k}'")
    return p, w


# --- settings: factory defaults < config.yml < variables, with where each value came from -------

def var_overlay(pipeline: dict, variables: dict) -> dict:
    """Repository variables as a config-shaped dict."""
    out: dict = {}

    def put(path: str, value):
        node = out
        keys = path.split(".")
        for k in keys[:-1]:
            node = node.setdefault(k, {})
        node[keys[-1]] = value

    def conv(path: str, raw: str):
        if path in ("verify", "updates.check"):
            return raw.strip().lower() == "true"
        if path.startswith("features."):
            return [x.strip() for x in raw.split(",") if x.strip()]
        if path.endswith("small_change_lines"):
            return int(raw)
        return raw.strip()

    for var, path in (pipeline.get("variables") or {}).items():
        raw = variables.get(var)
        if raw in (None, ""):
            continue
        if "*" in path:
            for name, st in pipeline["stages"].items():
                cond = path.split(".")[3]
                if cond in (st.get("when") or {}):
                    put(path.replace("*", name), conv(path, raw))
        else:
            put(path, conv(path, raw))
    for name in pipeline["stages"]:
        up = name.upper().replace("-", "_")
        for kind, key in (("MODEL", "model"), ("EFFORT", "effort")):
            raw = variables.get(f"FACTORY_{kind}_{up}")
            if raw:
                put(f"stages.{name}.{key}", raw.strip())
    return out


def layered(pipeline: dict, cfg: dict | None, variables: dict) -> tuple[dict, dict]:
    """Merge defaults, config.yml and variables; return (settings, sources by dotted path)."""
    cfg = norm_config(cfg or {})
    for name, level in (cfg.pop("effort", None) or {}).items():  # `effort: {triage: high}` shorthand
        cfg.setdefault("stages", {}).setdefault(name, {}).setdefault("effort", level)
    settings: dict = {}
    sources: dict = {}

    def merge(node: dict, overlay: dict, src: str, prefix: str):
        for k, v in overlay.items():
            path = f"{prefix}{k}"
            if isinstance(v, dict):
                merge(node.setdefault(k, {}), v, src, path + ".")
            else:
                node[k] = v
                sources[path] = src

    defaults = copy.deepcopy(pipeline.get("defaults") or {})
    defaults["autonomy"] = pipeline["autonomy"]["default"]
    merge(settings, defaults, "factory default", "")
    merge(settings, cfg, "config.yml", "")
    merge(settings, var_overlay(pipeline, variables), "variable", "")
    return settings, sources


def resolve_flags(features: dict, settings: dict, variables: dict) -> tuple[dict, dict, list]:
    """(flags on/off, why, undecided flag ids)."""
    f = settings.get("features") or {}
    cfg_on, cfg_off = set(f.get("on") or []), set(f.get("off") or [])
    var_off = {x.strip() for x in (variables.get("FACTORY_FEATURES_OFF") or "").split(",") if x.strip()}
    var_on = {x.strip() for x in (variables.get("FACTORY_FEATURES_ON") or "").split(",") if x.strip()}
    preview = f.get("preview") or []
    flags, why, undecided = {}, {}, []
    for flag, spec in features.items():
        state = spec["state"]
        if flag in var_off:
            flags[flag], why[flag] = False, "variable FACTORY_FEATURES_OFF"
        elif flag in var_on:
            flags[flag], why[flag] = True, "variable FACTORY_FEATURES_ON"
        elif flag in cfg_off:
            flags[flag], why[flag] = False, "config.yml features.off"
        elif flag in cfg_on:
            flags[flag], why[flag] = True, "config.yml features.on"
        elif state == "preview" and (preview == "all" or flag in preview):
            flags[flag], why[flag] = True, "config.yml features.preview"
        else:
            flags[flag], why[flag] = state == "default", f"features.yaml ({state})"
        if flag not in cfg_on | cfg_off | var_on | var_off:
            undecided.append(flag)
    return flags, why, undecided


# --- matching an event to a stage ----------------------------------------------------------------

def match_trigger(st: dict, event_name: str, event: dict, params: dict, item_labels: list, variables: dict):
    """The trigger this event fires, or (None, reason)."""
    for trig in st["triggers"]:
        ev = trig["event"]
        if ev == "dispatch" and event_name == "workflow_dispatch":
            return trig, "dispatch"
        if ev == "item.opened" and event_name == "issues" and event.get("action") == "opened":
            assoc = (event.get("issue") or {}).get("author_association")
            if trig.get("authors") and assoc not in trig["authors"] and \
                    variables.get(trig.get("all_authors_variable", "")) != "true":
                return None, f"opened by {assoc}, not {'/'.join(trig['authors'])}"
            return trig, "issue opened"
        if ev == "item.labeled" and event_name == "issues" and event.get("action") == "labeled":
            if (event.get("label") or {}).get("name") != trig["label"]:
                continue
            if trig.get("requires") and trig["requires"] not in item_labels:
                return None, f"'{trig['label']}' added, but the item isn't {trig['requires']}"
            return trig, f"'{trig['label']}' added"
        if ev == "pr.changed" and event_name in ("pull_request_target", "pull_request") and \
                event.get("action") in trig["types"]:
            return trig, f"pull request {event.get('action')}"
        if ev == "schedule" and event_name == "schedule":
            return trig, "schedule"
        if ev == "repository_dispatch" and event_name == "repository_dispatch" and event.get("action") == trig["type"]:
            return trig, f"repository_dispatch {trig['type']}"
        if ev == "call" and event_name != "workflow_dispatch" and params:
            return trig, "called by another workflow"
    return None, f"no trigger of this stage matches {event_name}"


def stage_params(name: str, st: dict, event_name: str, event: dict, params: dict, server: str) -> dict:
    """The stage's inputs, validated: they reach prompts and shells."""
    if name == "dependency-bump":
        src = event.get("client_payload") if event_name == "repository_dispatch" else params
        src = src or {}
        out = {k: str(src.get(k, "")) for k in ("source_repo", "package", "tag")}
        brk = src.get("breaking")
        out["breaking"] = "true" if brk in (True, "true") else "false" if brk in (False, "false") else ""
        checks = {"source_repo": r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$", "package": r"^(@[a-z0-9_.-]+/)?[A-Za-z0-9_.-]+$",
                  "tag": r"^[A-Za-z0-9_./-]+$", "breaking": r"^(true|false)$"}
        for k, rx in checks.items():
            if not re.match(rx, out[k]):
                raise FactoryError(f"bad {k} {out[k]!r}")
        out["version"] = out["tag"].split("-v")[-1] if "-v" in out["tag"] else out["tag"].lstrip("v")
        out["release_url"] = f"{server}/{out['source_repo']}/releases/tag/{out['tag']}"
        return out
    if name == "improve-review":
        hours = str(params.get("since_hours") or "168")
        if not hours.isdigit():
            raise FactoryError(f"bad since_hours {hours!r}")
        return {"since_hours": hours}
    if name == "notify-consumers":
        out = {"tag": str(params.get("tag", "")), "package": str(params.get("package", ""))}
        if not re.match(r"^[A-Za-z0-9_./-]+$", out["tag"]) or not re.match(r"^(@[a-z0-9_.-]+/)?[A-Za-z0-9_.-]+$", out["package"]):
            raise FactoryError("bad tag or package")
        return out
    return {}


# --- the plan --------------------------------------------------------------------------------------

def expand_tools(pipeline: dict, tools: list, verify: bool, runtime: str) -> tuple[list, str]:
    out, mcp = [], ""
    for t in tools:
        prof = pipeline["tool_profiles"].get(t)
        if isinstance(prof, dict):  # browser
            if verify and runtime == "actions":
                out += prof["tools"]
                mcp = f".claude/skills/{prof['mcp']}"
            continue
        for x in (prof if prof is not None else [t]):
            if x not in out:
                out.append(x)
    return out, mcp


def render_prompt(template: str, values: dict, where: str) -> str:
    def sub(m):
        key = m.group(1).strip()
        if key not in values:
            raise FactoryError(f"{where}: unknown placeholder {{{{{key}}}}}")
        return str(values[key])
    return re.sub(r"\{\{\s*([A-Za-z0-9_.-]+)\s*\}\}", sub, template)


def model_for(value: str, tiers: dict) -> str:
    model = tiers.get(value, value)
    if not SAFE.match(model):
        raise FactoryError(f"bad model {model!r}")
    return model


def resolve(ctx: dict, root: Path = FACTORY_ROOT) -> dict:
    """Resolve one run. ctx: stage, event_name, event, params, variables, config, item, repository,
    server_url, run_id, factory {repo, sha, ref, release}, files {path: exists}, tags, dry_run."""
    pipeline, features = ctx.get("pipeline") or load_pipeline(root), ctx.get("features") or load_features(root)
    name = ctx["stage"]
    if name not in pipeline["stages"]:
        raise FactoryError(f"no stage '{name}' in pipeline.yaml")
    st = pipeline["stages"][name]
    variables = ctx.get("variables") or {}
    problems, _ = validate_config(ctx.get("config"), pipeline, features)
    if problems:
        raise FactoryError("config.yml: " + "; ".join(problems))
    settings, sources = layered(pipeline, ctx.get("config"), variables)
    flags, flag_why, undecided = resolve_flags(features, settings, variables)
    scfg = (settings.get("stages") or {}).get(name) or {}
    item = ctx.get("item") or {}
    labels = list(item.get("labels") or [])
    server, repo = ctx.get("server_url", "https://github.com"), ctx["repository"]
    plan = {"stage": name, "run": False, "reason": "", "item": item.get("number") or "", "item_kind": st["item"],
            "factory": ctx.get("factory") or {}, "flags": {k: v for k, v in flags.items()}, "sources": {},
            "dry_run": bool(ctx.get("dry_run"))}
    if st["item"] == "pr":
        plan["pr"] = {"base_sha": item.get("base_sha", ""), "head_sha": item.get("head_sha", "")}
    src = plan["sources"]

    trig, why = match_trigger(st, ctx["event_name"], ctx.get("event") or {}, ctx.get("params") or {}, labels, variables)
    plan["trigger"] = why
    skip = None
    if trig is None:
        skip = why
    elif scfg.get("enabled") is False:
        skip = f"stages.{name}.enabled is false ({sources.get(f'stages.{name}.enabled')})"
    elif st.get("feature") and not flags.get(st["feature"]):
        skip = f"flag {st['feature']} is off"
    elif st.get("requires_state") and st["requires_state"] not in labels:
        if ctx["event_name"] == "workflow_dispatch":
            raise FactoryError(f"#{item.get('number')} is not labeled {st['requires_state']}")
        skip = f"the item isn't {st['requires_state']}"
    elif st.get("eligible") and item:
        e = st["eligible"]
        if e.get("open") and item.get("state") != "open":
            skip = "the pull request isn't open"
        elif e.get("draft") is False and item.get("draft"):
            skip = "the pull request is a draft"
        elif any((item.get("head_ref") or "").startswith(p) for p in e.get("skip_head_prefixes", [])):
            skip = f"head branch {item.get('head_ref')} is skipped"
    elif st.get("requires_file") and not (ctx.get("files") or {}).get(st["requires_file"]):
        skip = f"no {st['requires_file']} in this repository; run the {st.get('skill')} skill locally first"
    params = stage_params(name, st, ctx["event_name"], ctx.get("event") or {}, ctx.get("params") or {}, server) if skip is None else {}
    plan["params"] = params

    # Runtime: pipeline < config.yml < the trigger < a runtime label on the item.
    runtime, src["runtime"] = st.get("runtime", "actions"), "pipeline.yaml"
    if scfg.get("runtime"):
        runtime, src["runtime"] = scfg["runtime"], sources.get(f"stages.{name}.runtime")
    if trig and trig.get("runtime"):
        runtime, src["runtime"] = trig["runtime"], f"trigger ({why})"
    for lab, rt in (pipeline.get("runtime_labels") or {}).items():
        if lab in labels and "runtime" in st:
            runtime, src["runtime"] = rt, f"label {lab}"
    plan["runtime"] = runtime

    # Conditions, then the agent: pipeline values, then config.yml/variables, per condition in order.
    never = set(pipeline["autonomy"]["never_if"])
    small_lines = int(scfg.get("small_change_lines", st.get("small_change_lines", 0)))
    active = {
        "autonomous": pipeline["gate"]["agent"] in labels,
        "risk": bool(never & set(labels)),
        "small_change": bool(item) and item.get("changed_lines", 10**9) <= small_lines and not set(labels) & set(pipeline["markers"]),
        "breaking": params.get("breaking") == "true",
    }
    tiers = dict(pipeline["tiers"])
    tiers.update(settings.get("tiers") or {})
    agent = None if st.get("agent") == "none" else dict(st["agent"])
    apply_ops = list(st["apply"])
    conds = []
    if agent is not None:
        for key, label in (("tier", "tier"), ("effort", "effort")):
            src[f"agent.{label}"] = "pipeline.yaml"
        if scfg.get("model") or scfg.get("tier"):
            agent["tier"] = scfg.get("model") or scfg.get("tier")
            src["agent.tier"] = sources.get(f"stages.{name}.model") or sources.get(f"stages.{name}.tier")
        if scfg.get("effort"):
            agent["effort"], src["agent.effort"] = scfg["effort"], sources.get(f"stages.{name}.effort")
    for cond, over in (st.get("when") or {}).items():
        if not active.get(cond):
            continue
        conds.append(cond)
        if over.get("agent") == "none":
            agent = None
        if "apply" in over:
            apply_ops = list(over["apply"])
        if agent is None:
            continue
        cc = ((scfg.get("when") or {}).get(cond) or {})
        for key in ("tier", "effort"):
            if key in over:
                agent[key], src[f"agent.{key}"] = over[key], f"pipeline.yaml when.{cond}"
        if cc.get("model") or cc.get("tier"):
            agent["tier"] = cc.get("model") or cc.get("tier")
            src["agent.tier"] = (sources.get(f"stages.{name}.when.{cond}.model")
                                 or sources.get(f"stages.{name}.when.{cond}.tier")) + f" (when.{cond})"
        if cc.get("effort"):
            agent["effort"] = cc["effort"]
            src["agent.effort"] = sources.get(f"stages.{name}.when.{cond}.effort") + f" (when.{cond})"
    plan["conditions"] = conds

    verify = bool(settings.get("verify"))
    src["verify"] = sources.get("verify")
    out_kind = st["output"]["kind"]
    if agent is not None:
        tools, mcp = expand_tools(pipeline, agent["tools"], verify and "browser" in agent["tools"], runtime)
        model = model_for(agent["tier"], tiers)
        schema_path = st["output"].get("schema") or ("stages/_output/patch.schema.json" if out_kind == "patch" else "")
        schema = json.dumps(json.loads((root / schema_path).read_text()), separators=(",", ":")) if schema_path else ""
        plan["agent"] = {"skill": st["skill"], "tier": agent["tier"] if agent["tier"] in tiers else "",
                         "model": model, "effort": agent["effort"], "max_turns": agent["max_turns"],
                         "allowed_tools": ",".join(tools), "mcp_config": mcp, "json_schema": schema,
                         "setup": bool(agent.get("setup")), "bun": bool(agent.get("bun"))}
        args = [f"--model {model}", f"--max-turns {agent['max_turns']}", f'--allowedTools "{",".join(tools)}"']
        if mcp:
            args.append(f"--mcp-config {mcp}")
        if schema:
            args.append(f"--json-schema '{schema}'")
        plan["claude_args"] = "\n".join(args)
    else:
        plan["agent"] = None
        plan["claude_args"] = ""
    plan["output"] = {"kind": out_kind if agent is not None else "none", **{k: v for k, v in st["output"].items() if k != "kind"}}

    # Autonomy (triage's route): the policy and the rules whose flag is on.
    policy = settings["autonomy"]
    src["autonomy"] = sources.get("autonomy")
    rules = [r for r in pipeline["autonomy"]["policies"][policy] if not r.get("feature") or flags.get(r["feature"])]
    next_stage = {s["requires_state"]: n for n, s in pipeline["stages"].items() if s.get("requires_state")}
    plan["autonomy"] = {"policy": policy, "rules": rules, "never_if": sorted(never), "next_stage": next_stage}

    # The prompt, the same for every runtime.
    if agent is not None and skip is None:
        def backticks(xs):
            return ", ".join(f"`{x}`" for x in xs)
        item_url = f"{server}/{repo}/{'pull' if st['item'] == 'pr' else 'issues'}/{item.get('number')}" if item else ""
        local_verify = "use gstack /browse if it is available in this session, the change has a UI, and FACTORY.md has an App section"
        values = {"repository": repo, "item": item.get("number", ""), "item_url": item_url,
                  "run_url": f"{server}/{repo}/actions/runs/{ctx.get('run_id', '')}", "model": plan["agent"]["model"],
                  "skill": f".claude/skills/{st['skill']}/SKILL.md", "tracker": "factory tracker",
                  "states": backticks(pipeline["states"]), "markers": backticks(pipeline["markers"]),
                  "verify": local_verify if runtime == "local" else (
                      "yes (Playwright MCP; write evidence under verification/)" if plan["agent"]["mcp_config"]
                      else "no (skip verify-behavior and say so)"),
                  "pr.base_sha": item.get("base_sha", ""), "pr.head_sha": item.get("head_sha", ""), "features": ""}
        values.update({f"gate.{k}": v for k, v in pipeline["gate"].items()})
        values.update({f"params.{k}": v for k, v in params.items()})
        frags = [root / "skills" / st["skill"] / "features" / f"{f}.md" for f, on in flags.items() if on]
        values["features"] = "\n\n".join(p.read_text().strip() for p in frags if p.exists())
        out_file = root / "stages" / "_output" / f"{out_kind}.{runtime}.md"
        values["output"] = render_prompt(out_file.read_text(), values, str(out_file)).strip() if out_file.exists() else ""
        prompt_file = root / "stages" / name / "prompt.md"
        plan["prompt"] = render_prompt(prompt_file.read_text(), values, f"stages/{name}/prompt.md").strip() + "\n"
    else:
        plan["prompt"] = ""

    if runtime == "local":
        loc = (settings.get("runtimes") or {}).get("local") or {}
        plan["local"] = {"setting_sources": loc.get("setting_sources", "project,local"), "work_dir": loc.get("work_dir", ""),
                         "session_name": f"{repo}#{item.get('number')} {name}", "worktree": f"gh-{item.get('number')}"}
        src["local.setting_sources"] = sources.get("runtimes.local.setting_sources")
        apply_ops = []  # detached: the session writes for itself
    elif st.get("gated"):
        apply_ops.append("clear-gate")

    plan["update"] = update_check(ctx, settings, features, undecided)
    if plan["update"]["needed"] and runtime != "local":
        apply_ops.append("open-update-issue")
    for op in apply_ops:
        if op not in APPLY_OPS:
            raise FactoryError(f"stage {name}: unknown apply operation {op}")
    plan["apply"] = apply_ops
    plan["timeout"] = st.get("timeout", 30)
    plan["settle_seconds"] = (trig or {}).get("settle_seconds", 0) if ctx["event_name"] != "workflow_dispatch" else 0
    plan["flag_sources"] = flag_why
    plan["run"], plan["reason"] = (skip is None), (skip or why)
    return plan


# --- the update check (rollout.md §6.2) -----------------------------------------------------------

def parse_version(tag: str):
    m = re.match(r"^v(\d+)\.(\d+)(?:\.(\d+))?$", tag)
    return tuple(int(x) for x in m.groups() if x is not None) if m else None


def update_check(ctx: dict, settings: dict, features: dict, undecided: list) -> dict:
    fac = ctx.get("factory") or {}
    ref = fac.get("ref", "")
    tags = ctx.get("tags") or {}  # {tag: sha}
    current = ref.removeprefix("refs/tags/").removeprefix("refs/heads/")
    lines = sorted({v[:2] for t in tags if (v := parse_version(t)) and v[0] == 0} |
                   {(v[0],) for t in tags if (v := parse_version(t)) and v[0] > 0 and len(v) == 2})
    cur = parse_version(current)
    newer = None
    if cur and lines:
        key = cur[:2] if cur[0] == 0 else cur[:1]
        top = lines[-1]
        if top > key:
            newer = "v" + ".".join(map(str, top))
    pending = [{"id": f, "summary": features[f]["summary"], "state": features[f]["state"],
                "cost": features[f].get("cost", ""), "added": features[f].get("added", "")} for f in undecided]
    check = bool((settings.get("updates") or {}).get("check", True))
    needed = check and bool(newer or pending)
    body = ""
    if needed:
        url = f"{ctx.get('server_url', 'https://github.com')}/{fac.get('repo', '')}"
        out = ["The factory has an update for this repository. Nothing changes until you act on it.", "",
               f"- **Running:** `{current or 'unknown'}` ({fac.get('release') or 'unreleased'}, `{fac.get('sha', '')[:12]}`)"]
        if newer:
            out += [f"- **Available:** `{newer}`, a new minor line with breaking changes. "
                    f"[Release notes]({url}/releases), [MIGRATION.md]({url}/blob/{newer}/MIGRATION.md).",
                    "", f"To adopt it, follow MIGRATION.md, then run `factory update --to {newer}` in a clone and merge the result."]
        if pending:
            out += ["", "## Flags this repository hasn't decided on", "",
                    "Put each one under `features.on` or `features.off` in `.github/factory/config.yml` to settle it.", ""]
            for p in pending:
                now = "on now" if p["state"] == "default" else "off until you opt in"
                opt = f"features: {{off: [{p['id']}]}}" if p["state"] == "default" else f"features: {{on: [{p['id']}]}}"
                out.append(f"- [ ] `{p['id']}` ({p['state']}, {now}): {p['summary']} Cost: {p['cost'] or 'none'}. `{opt}`")
        out += ["", "_Opened by the factory's plan job. `updates: {check: false}` in config.yml turns this off._"]
        body = "\n".join(out)
        digest = hashlib.sha256(body.encode()).hexdigest()[:12]
        body += f"\n<!-- factory:update {digest} -->\n"
    return {"needed": needed, "current": current, "newer_line": newer, "pending": [p["id"] for p in pending], "body": body}


# --- the job summary ------------------------------------------------------------------------------

def summary(plan: dict) -> str:
    f = plan.get("factory") or {}
    out = [f"### Factory: {plan['stage']}", "",
           f"Factory `{f.get('repo', '')}` at `{f.get('sha', '')[:12]}` ({f.get('ref', '')}; release {f.get('release') or 'none'}).", "",
           f"**{'Runs' if plan['run'] else 'Skipped'}:** {plan['reason']}." + (" Dry run: the apply job is skipped." if plan["dry_run"] else ""), ""]
    if plan["run"]:
        a = plan.get("agent") or {}
        rows = [("item", plan.get("item") or "none", ""), ("runtime", plan["runtime"], plan["sources"].get("runtime")),
                ("conditions", ", ".join(plan["conditions"]) or "none", "")]
        if a:
            rows += [("model", f"{a['model']} ({a['tier'] or 'model ID'})", plan["sources"].get("agent.tier")),
                     ("effort", a["effort"], plan["sources"].get("agent.effort")), ("max turns", a["max_turns"], "pipeline.yaml"),
                     ("tools", a["allowed_tools"], "pipeline.yaml tool_profiles")]
        rows += [("autonomy", plan["autonomy"]["policy"], plan["sources"].get("autonomy")),
                 ("apply", ", ".join(plan["apply"]) or "none", "pipeline.yaml")]
        out += ["| | value | from |", "|---|---|---|"] + [f"| {k} | `{v}` | {s or ''} |" for k, v, s in rows]
    on = [f"`{k}` ({plan['flag_sources'][k]})" for k, v in plan["flags"].items() if v]
    out += ["", f"**Flags on:** {', '.join(on) or 'none'}"]
    u = plan["update"]
    out += [f"**Update:** {'pending' if u['needed'] else 'none'}" +
            (f" (newer line {u['newer_line']})" if u.get("newer_line") else "") +
            (f" (undecided flags: {', '.join(u['pending'])})" if u.get("pending") else "")]
    if plan.get("prompt"):
        out += ["", "<details><summary>Prompt</summary>", "", "~~~~markdown", plan["prompt"], "~~~~", "</details>"]
    return "\n".join(out) + "\n"


